#!/usr/bin/env python3
"""gen_manual_index.py — the reference manual's index, READ off the manual instead of typed.

WHAT WAS WRONG WITH THE HAND-WRITTEN ONE. `reference_manual/README.md` was 173 lines in which a
person typed every page name, every status and every count, and measured 2026-10-04 it was the
largest single source of false statements in this repository:

  * "only 3 of 19 [canons] do anything today" — `canon_library.md` said "20 defined, 20 described,
    17 implemented" and `check_canon_documented.py` run that day said "defined 21 described 20
    implemented 18". THREE numbers for one fact, and the one in the index was the furthest out.
  * "20 notions, 119 terms" and "It is green: 20 of 20" — `mac_vocabulary.yaml` carries 24 notions
    holding 144 terms, and four of those notions have no chapter at all.
  * nine of the manual's pages were MISSING from the index entirely, among them the only two canons
    the runtime SHIPS — `resolve_by_register`, which every name resolution in every bundle goes
    through, and `enum_from_register` — while twelve reference-only canons were listed.
  * two live generated artifacts, `column_bench.html` and `grammar_map.html`, were linked from no
    page in the directory, and the 56-page generated key reference under `keys/` was unreachable.
  * 19 pattern pages were marked "written" while all 19 carry `status: prototype` themselves.

NO NUMBER ON THE PAGE THIS WRITES IS TYPED HERE. The page list is a filesystem walk. Each page's
status is that page's OWN `status:` frontmatter, quoted. The canon counts come from the three lists
`check_canon_documented.py` compares — `mac_vocabulary.yaml#canon`, `reference_manual/canon/*.md` and
`mac_runtime.canon.IMPLEMENTED`. The vocabulary counts come from `mac_vocabulary.yaml` and from
`gen_vocabulary_terms.py`'s own block markers, imported rather than restated.

AND WHAT CANNOT BE READ IS ON THE PAGE. Measured 2026-10-04, five files of the manual yield no
status at all — two markdown pages carry no frontmatter, two are HTML artifacts and one is a YAML
declaration — and one more carries frontmatter that is not valid YAML, so its `status:` line is read
literally and SAID to have been read that way. All six are listed as DECLARED UNKNOWNS with the
reason, because an index that quietly guesses is the thing this replaces.

THE CHECK DOES NOT ONLY RE-RENDER. Byte-comparing the page against a fresh render catches a page
someone edited and CANNOT catch this renderer dropping a page — which is the measured defect it
exists to prevent: `gen_schema_shapes.py --check` reports `shape_reference.md` current while the
page omits a key the schema has carried since 2026-09-28, because the comparator and the renderer
are the same code. So `--check` also walks the filesystem and asserts, against the LINK TARGETS
parsed out of the page on disk, that every page appears in the index — and that every page of the
`keys/` subtree is reachable through the sub-index this page delegates to. Different questions,
different evidence, so they cannot agree by construction.

    python3 tools/gen_manual_index.py                 # write reference_manual/README.md
    python3 tools/gen_manual_index.py --check         # exit 1 if stale or incomplete
    python3 tools/gen_manual_index.py --self-test     # one mutant per reject class + a clean fixture
"""
