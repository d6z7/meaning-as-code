TOOLS = SELF.parent
ROOT = TOOLS.parent

#: The files of the manual a reader can open. `.yaml` is here because the manual carries one —
#: `column_effects.yaml` — and leaving a whole file out of a completeness claim is the defect.
PAGE_SUFFIXES = (".md", ".html", ".yaml")

BANNER = "<!-- GENERATED by tools/gen_manual_index.py — do not edit; regenerate. -->"
LINK_RE = re.compile(r"\]\(([^)\s]+)\)")
#: A GENERATOR ATTRIBUTION, not merely a mention. `tools/gen_x.py` has to appear on a line that also
#: says GENERATED / generated by / generated_by — which is how every generated page in this manual
#: signs itself. Matching the bare path instead credited `column_effects.yaml` to the generator that
#: READS it ("CONSUMED BY tools/gen_column_bench.py"), i.e. it invented a false statement of exactly
#: the kind this page exists to delete.
GEN_RE = re.compile(r"^(?=.*(?:GENERATED|generated by|generated_by)).*?tools/(gen_[a-z0-9_]+)\.py",
                    re.M)
H1_RE = re.compile(r"^#\s+(.*)$", re.M)
HTML_TITLE_RE = re.compile(r"<title>(.*?)</title>", re.S)
STATUS_LINE_RE = re.compile(r"^status:\s*(.*)$", re.M)
#: No leading `\b`: `v0.1.12` has no word boundary between `v` and `0`, so a `\b` anchored pattern
#: found 2 of the 5 versions `shape_reference.md` actually names.
SEMVER_RE = re.compile(r"(?<![\d.])\d+\.\d+\.\d+(?![\d.])")
FINDING_RE = re.compile(r"^##\s+(F\d+\s+—.*)$", re.M)

CELL_WIDTH = 104          # a presentation choice, not a fact about the manual


class CouldNotRun(Exception):
    """A source this index is DERIVED FROM is unreadable. Exit 2 — never a verdict."""


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# where things are, derived from one root so the self-test fixture is a real repository
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def manual_dir(root: pathlib.Path) -> pathlib.Path:
    return root / "reference_manual"


def index_path(root: pathlib.Path) -> pathlib.Path:
    return manual_dir(root) / "README.md"


def keys_index_path(root: pathlib.Path) -> pathlib.Path:
    return manual_dir(root) / "keys" / "README.md"


def manual_files(root: pathlib.Path) -> list[pathlib.Path]:
    """Every openable file of the manual, keys/ included. Sorted, so the page is deterministic."""
    return sorted(p for p in manual_dir(root).rglob("*")
                  if p.is_file() and p.suffix in PAGE_SUFFIXES)


def under_keys(root: pathlib.Path, path: pathlib.Path) -> bool:
    return "keys" in path.relative_to(manual_dir(root)).parts


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# reading what each page says about itself
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def front_matter(text: str) -> tuple[dict | None, str | None]:
    """(parsed frontmatter or None, raw frontmatter block or None)."""
    if not text.startswith("---"):
        return None, None
    end = text.find("\n---", 3)
    if end < 0:
        return None, None
    block = text[text.index("\n") + 1:end]
    try:
        parsed = yaml.safe_load(block)
    except yaml.YAMLError:
        return None, block
    return (parsed if isinstance(parsed, dict) else None), block


def status_from_block(block: str) -> str | None:
    """`status:` read as a literal line, for frontmatter YAML cannot parse.

    Not a guess: the line IS the declaration. The page records that it was read this way, so a
    reader can tell a parsed status from a scraped one.
    """
    m = STATUS_LINE_RE.search(block)
    if not m:
        return None
    out = [m.group(1)]
    for line in block[m.end():].splitlines()[1:]:
        if re.match(r"^\S", line):
            break
        out.append(line.strip())
    return " ".join(x for x in out if x).strip() or None


def describe(path: pathlib.Path, base: pathlib.Path) -> dict:
    """One page, as the page itself declares it. `how` records WHERE the status came from."""
    text = path.read_text(encoding="utf-8", errors="replace")
    title = status = None
    how = "absent"

    if path.suffix == ".md":
        parsed, block = front_matter(text)
        if parsed is not None:
            title = parsed.get("title")
            raw = parsed.get("status")
            if raw is None:
                how = "absent (its frontmatter carries no status: key)"
            else:
                status, how = str(raw), "frontmatter"
        elif block is not None:
            status = status_from_block(block)
            how = ("frontmatter-line (its frontmatter is not valid YAML, so the status: line was "
                   "read literally)") if status else \
                  "unreadable (its frontmatter is not valid YAML and carries no status: line)"
        else:
            how = "absent (the page carries no frontmatter)"
        if not title:
            m = H1_RE.search(text)
            title = m.group(1).strip() if m else None
    elif path.suffix == ".html":
        m = HTML_TITLE_RE.search(text)
        title = m.group(1).strip() if m else None
        how = "absent (an HTML artifact carries no frontmatter)"
    else:
        first = next((ln for ln in text.splitlines() if ln.startswith("#")), "")
        title = first.lstrip("# ").strip() or None
        how = "absent (a YAML declaration carries no frontmatter)"

    return {"rel": path.relative_to(base).as_posix(), "title": title, "status": status, "how": how,
            "generators": sorted(set(GEN_RE.findall(text))),
            "lines": len(text.splitlines())}


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# reading the declarations the gates already read
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def canon_lists(root: pathlib.Path) -> dict:
    """The THREE canon lists `check_canon_documented.py` compares, from the same three sources."""
    vocab_file = root / "mac_vocabulary.yaml"
    pages_dir = manual_dir(root) / "canon"
    if not vocab_file.is_file() or not pages_dir.is_dir():
        raise CouldNotRun(f"need {vocab_file.name} and {pages_dir}")
    block = (yaml.safe_load(vocab_file.read_text(encoding="utf-8")) or {}).get("canon") or {}
    # `terms:` is the vocabulary's key; `members:` is the older spelling, read the same way the
    # canon gate reads it — one wrong key there once reported 19 defined canons as 0.
    defined = block.get("terms") if block.get("terms") is not None else (block.get("members") or {})
    described = {p.stem for p in pages_dir.glob("*.md")}

    sys.path.insert(0, str(TOOLS))
    try:
        import _neighbours
        _neighbours.ensure_runtime_on_path()
        from mac_runtime.canon import IMPLEMENTED
    except ImportError as exc:
        # THE SAME REFUSAL `check_canon_documented.py` MAKES. "Implemented" is the number the old
        # index got most wrong ("only 3 of 19 do anything today"); rendering the page without it
        # would swap a wrong number for a silent omission, and a page whose content depended on
        # whether the runtime happened to be reachable could never be byte-compared by a gate.
        raise CouldNotRun(f"mac_runtime.canon is not importable ({exc}). The implemented list is the "
                          f"one source this index cannot do without; set $MAC_RUNTIME_SRC.")
    return {"defined": dict(defined), "described": described,
            "honoured": {name.rsplit(".", 1)[-1] for name in IMPLEMENTED}}


def vocabulary_lists(root: pathlib.Path) -> dict:
    """Notions, their terms, and WHICH PAGE documents each.

    A notion is a top-level entry of `mac_vocabulary.yaml` that declares a `kind:`. Measured on this
    vocabulary that is exactly the set `gen_vocabulary_terms.py` renders, and it is inclusive rather
    than a restated list of kinds: a NEW kind shows up here instead of being silently dropped. The
    notion-to-page map is read from that generator's own block markers, imported not restated.
    """
    sys.path.insert(0, str(TOOLS))
    try:
        import gen_vocabulary_terms as gvt
    except ImportError as exc:                                 # pragma: no cover
        raise CouldNotRun(f"gen_vocabulary_terms is not importable ({exc})")
    vocab_file = root / "mac_vocabulary.yaml"
    if not vocab_file.is_file():
        raise CouldNotRun(f"need {vocab_file}")
    vocab = yaml.safe_load(vocab_file.read_text(encoding="utf-8")) or {}
    notions = {k: v for k, v in vocab.items() if isinstance(v, dict) and v.get("kind")}
    where: dict[str, list[str]] = {}
    for page in sorted(manual_dir(root).glob("*.md")):
        for m in gvt.BLOCK.finditer(page.read_text(encoding="utf-8", errors="replace")):
            where.setdefault(m.group("notion"), []).append(page.name)
    return {"notions": notions, "where": where}


def suite_visible_generators(root: pathlib.Path) -> set[str]:
    """Which gen_*.py a `check_*.py` delegates to — i.e. which ones the suite can see at all.

    `run_framework_gates.sh` discovers gates by globbing `check_*.py`, so a generator's own
    `--check` is invisible to the suite unless some checker imports it. Read, not assumed.
    """
    seen: set[str] = set()
    for p in sorted((root / "tools").glob("check_*.py")):
        text = p.read_text(encoding="utf-8", errors="replace")
        seen.update(m.group(1) for m in re.finditer(r"import\s+(gen_[a-z0-9_]+)", text))
    return seen


def findings(root: pathlib.Path) -> list[str]:
    f = manual_dir(root) / "FINDINGS.md"
    if not f.is_file():
        return []
    return [m.group(1).strip() for m in FINDING_RE.finditer(f.read_text(encoding="utf-8"))]


def shape_version_note(root: pathlib.Path, schema_version) -> str:
    """What `shape_reference.md` NAMES, measured. The index used to call its shapes always current."""
    p = manual_dir(root) / "shape_reference.md"
    if not p.is_file() or not schema_version:
        return ""
    found = sorted(set(SEMVER_RE.findall(p.read_text(encoding="utf-8", errors="replace"))),
                   key=lambda v: tuple(int(x) for x in v.split(".")))
    if not found:
        return "`shape_reference.md` names no schema version."
    named = ", ".join(f"`{v}`" for v in found)
    if schema_version in found:
        return f"`shape_reference.md` names {named}, the current one among them."
    return (f"`shape_reference.md` names {named} and **not** `{schema_version}`: the block "
            f"`gen_schema_shapes.py` writes is held current by its own `--check`, the prose around "
            f"it is not held by anything.")


