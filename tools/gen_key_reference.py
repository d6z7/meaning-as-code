def load(root: pathlib.Path):
    schema = json.loads((root / "mac.schema.json").read_text(encoding="utf-8"))
    vocab = yaml.safe_load((root / "mac_vocabulary.yaml").read_text(encoding="utf-8")) or {}
    return schema, vocab


def harvest_vocabulary(vocab: dict):
    """(notions, dotted) — the vocabulary indexed the way a concept actually spells a value.

    A concept writes `mac.concept.column.measure_type.flow`. The vocabulary files that under the
    notion `concept.column.measure_type` with the term `flow`, so the dotted name is `mac.` and
    the two joined. Indexing it this way means a NEW notion needs no change in this file.
    """
    notions: dict[str, dict] = {}
    dotted: dict[str, dict] = {}

    def walk(node, path=""):
        if not isinstance(node, dict):
            return
        terms = node.get("terms")
        if isinstance(terms, dict):
            entry = {"description": node.get("description"),
                     "closed": bool(node.get("closed")), "terms": {}}
            for term, body in terms.items():
                definition = body if isinstance(body, str) else (
                    (body or {}).get("definition") or (body or {}).get("description"))
                extra = ({k: v for k, v in body.items()
                          if k not in ("definition", "description")}
                         if isinstance(body, dict) else {})
                t = {"notion": path, "term": term, "definition": definition, "extra": extra}
                entry["terms"][term] = t
                dotted[f"mac.{path}.{term}"] = t
                dotted.setdefault(term, t)
            notions[path] = entry
        for k, v in node.items():
            if k != "terms":
                walk(v, f"{path}.{k}" if path else str(k))

    walk(vocab)
    return notions, dotted


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# the schema walk
# ──────────────────────────────────────────────────────────────────────────────────────────────────

class Walker:
    def __init__(self, schema: dict, dotted: dict):
        self.defs = schema["$defs"]
        self.dotted = dotted
        self.levels: dict[str, dict] = {}
        self.gaps: list[dict] = []

    def deref(self, node, guard: int = 0):
        while isinstance(node, dict) and guard < 16:
            guard += 1
            if "$ref" in node:
                node = self.defs.get(node["$ref"].split("/")[-1], {})
                continue
            if node.get("type") == "array" and "items" in node:
                node = node["items"]
                continue
            return node
        return node if isinstance(node, dict) else {}

    def shapes(self, node):
        """[(label, node)] — a key with several LEGAL shapes has several, not one.

        `grounding.sources[].columns` is why: it is a oneOf of a legacy flat list and the column
        map, and a reader shown only the first branch is shown the shape we are migrating away
        from.
        """
        n = self.deref(node)
        for comb in ("oneOf", "anyOf"):
            branches = n.get(comb)
            if isinstance(branches, list) and len(branches) > 1:
                out = []
                for i, sub in enumerate(branches):
                    d = self.deref(sub)
                    label = (d.get("title")
                             or (d.get("description") or "").split("—")[0].strip()[:52]
                             or f"form {i + 1}")
                    out.append((label, d))
                return out
        return [("", n)]

    def child_keys(self, node):
        props = dict(node.get("properties") or {})
        if props:
            return props, False
        #: `additionalProperties` IS the value's schema; `patternProperties` is a MAP of pattern to
        #: schema, so only the second needs unwrapping. Conflating them turned
        #: `additionalProperties: {"type": "string"}` into the string `"string"`, which is not a node
        #: — so three free-key levels could never carry a description and showed as permanent gaps.
        h = node.get("additionalProperties")
        if isinstance(h, dict) and h:
            return {ANY: h}, True
        h = node.get("patternProperties")
        if isinstance(h, dict) and h:
            return {ANY: list(h.values())[0]}, True
        return {}, False

    def type_of(self, resolved, raw):
        if isinstance(raw, dict) and raw.get("type") == "array":
            return f"list of {self.deref(raw).get('type') or 'object'}"
        return resolved.get("type") or (raw.get("type") if isinstance(raw, dict) else None) or "—"

    def walk(self, node, path: str, depth: int = 0):
        if depth > 8 or path in self.levels:
            return
        forms = []
        for label, resolved in self.shapes(node):
            props, is_map = self.child_keys(resolved)
            if props:
                forms.append((label, resolved, props, is_map))
        if not forms:
            return

        self.levels[path] = {"path": path, "forms": [], "depth": depth}
        for label, resolved, props, is_map in forms:
            required = set(resolved.get("required") or [])
            keys = []
            for key, raw in props.items():
                res = self.deref(raw)
                desc = (raw.get("description") if isinstance(raw, dict) else None) or res.get("description")
                enum = res.get("enum") or (raw.get("enum") if isinstance(raw, dict) else None)
                child = f"{path}.{key}"
                has_children = bool(self.child_keys(res)[0]) or len(self.shapes(raw)) > 1
                if not desc:
                    self.gaps.append({"level": path, "key": key})
                keys.append({
                    "key": key, "required": key in required,
                    "type": self.type_of(res, raw if isinstance(raw, dict) else {}),
                    "desc": desc,
                    "enum": [(e, self.dotted.get(e)) for e in enum] if enum else None,
                    "child": child if has_children else None,
                })
                self.walk(raw, child, depth + 1)
            self.levels[path]["forms"].append({
                "label": label, "free_key_map": is_map,
                "description": resolved.get("description"),
                "keys": sorted(keys, key=lambda k: (not k["required"], k["key"])),
            })



    def prune_children(self) -> None:
        """Drop a `child` link that names no level, AFTER the whole walk.

        `has_children` is decided before the child is walked, and it is optimistic: a key whose
        schema carries several branches counts as having children even when none of the branches
        turns out to hold named keys, so no level is ever created for it. Two links on
        `semantics/additivity.md` pointed at `additivity/each.md`, a page that was never written —
        caught by resolving every link from its own directory, not by any gate. The walk cannot
        know this in advance, so the honest fix is to decide afterwards from what exists.
        """
        for level in self.levels.values():
            for form in level["forms"]:
                for k in form["keys"]:
                    if k["child"] and k["child"] not in self.levels:
                        k["child"] = None


