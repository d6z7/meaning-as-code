#!/usr/bin/env python3
"""gen_key_reference.py — one page per LEVEL of a concept file, every key, cross-linked.

WHAT A READER ASKED FOR, and could not get. Starting at `concept:`, which keywords may I write
underneath, what does each mean, which are required, what are the legal values of each, and what
sits one level further down. Then the same for the level below, and the level below that. The
answer existed only as `mac.schema.json`, which a person does not read, and as prose pages that
split one column map four ways across 1,619 lines.

WHY IT IS GENERATED AND NOT WRITTEN. `reference_manual/shape_reference.md` is the hand-written
answer to this question and it omits `rulings` — a key the schema has carried since 2026-09-28 —
while `gen_schema_shapes.py --check` reports the page current, because the comparator and the
renderer are the same code and agree by construction. A key reference restated by hand is a second
home for the schema and it is the home that rots. So every key, type, requirement and enum here is
READ from the schema, every term definition from `mac_vocabulary.yaml`, and every example is CUT
from a real concept in a worked bundle. Nothing on these pages is typed by a person.

AND WHAT IS UNEXPLAINED IS PART OF THE OUTPUT. Measured 2026-10-04 on schema 0.1.16: of 200 keys
a concept may write, 82 carry no description at all — `metadata.owner`, `concept.definition`,
`measure.type`, `measure.unit`. A generator that hid those would render a reference manual whose
silences look like completeness. Each is emitted as a named gap, counted on the level it sits on
and totalled in the index, and the place to fix one is the schema.

THE CHECK DOES NOT ONLY RE-RENDER. Byte-comparing a page against a fresh render catches a page
that drifted from the schema and CANNOT catch the renderer dropping a key — that is the exact
defect above. So `--check` also asserts, independently of the renderer, that every key the schema
admits appears on exactly one page. Two different questions, two different rejects.

    python3 tools/gen_key_reference.py                     # write the pages
    python3 tools/gen_key_reference.py --check             # exit 1 if stale, missing or uncovered
    python3 tools/gen_key_reference.py --self-test         # one mutant per reject class
"""
