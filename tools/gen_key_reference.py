#: THE FREE-KEY SEGMENT. A level whose names the author chooses — a column name, an axis name —
#: is `<name>` in the schema walk and `each` in a filename, because `<` and `>` are not portable
#: in a path and a reader has to be able to type the name of the page they want.
ANY = "<name>"
ANY_SLUG = "each"

BANNER = "<!-- GENERATED by tools/gen_key_reference.py — do not edit; regenerate. -->"


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# the two declarations
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def load(root: pathlib.Path):
    schema = json.loads((root / "mac.schema.json").read_text(encoding="utf-8"))
    vocab = yaml.safe_load((root / "mac_vocabulary.yaml").read_text(encoding="utf-8")) or {}
    return schema, vocab


def harvest_vocabulary(vocab: dict):
    """(notions, dotted) — the vocabulary indexed the way a concept actually spells a value.

    A concept writes `mac.concept.column.measure_type.flow`. The vocabulary files that under the
    notion `concept.column.measure_type` with the term `flow`, so the dotted name is `mac.` and
    the two joined. Indexing it this way means a NEW notion needs no change in this file.
    """
    notions: dict[str, dict] = {}
    dotted: dict[str, dict] = {}

    def walk(node, path=""):
        if not isinstance(node, dict):
            return
        terms = node.get("terms")
        if isinstance(terms, dict):
            entry = {"description": node.get("description"),
                     "closed": bool(node.get("closed")), "terms": {}}
            for term, body in terms.items():
                definition = body if isinstance(body, str) else (
                    (body or {}).get("definition") or (body or {}).get("description"))
                extra = ({k: v for k, v in body.items()
                          if k not in ("definition", "description")}
                         if isinstance(body, dict) else {})
                t = {"notion": path, "term": term, "definition": definition, "extra": extra}
                entry["terms"][term] = t
                dotted[f"mac.{path}.{term}"] = t
                dotted.setdefault(term, t)
            notions[path] = entry
        for k, v in node.items():
            if k != "terms":
                walk(v, f"{path}.{k}" if path else str(k))

    walk(vocab)
    return notions, dotted


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# the schema walk
# ──────────────────────────────────────────────────────────────────────────────────────────────────

class Walker:
    def __init__(self, schema: dict, dotted: dict):
        self.defs = schema["$defs"]
        self.dotted = dotted
        self.levels: dict[str, dict] = {}
        self.gaps: list[dict] = []

    def deref(self, node, guard: int = 0):
        while isinstance(node, dict) and guard < 16:
            guard += 1
            if "$ref" in node:
                node = self.defs.get(node["$ref"].split("/")[-1], {})
                continue
            if node.get("type") == "array" and "items" in node:
                node = node["items"]
                continue
            return node
        return node if isinstance(node, dict) else {}

    def shapes(self, node):
        """[(label, node)] — a key with several LEGAL shapes has several, not one.

        `grounding.sources[].columns` is why: it is a oneOf of a legacy flat list and the column
        map, and a reader shown only the first branch is shown the shape we are migrating away
        from.
        """
        n = self.deref(node)
        for comb in ("oneOf", "anyOf"):
            branches = n.get(comb)
            if isinstance(branches, list) and len(branches) > 1:
                out = []
                for i, sub in enumerate(branches):
                    d = self.deref(sub)
                    label = (d.get("title")
                             or (d.get("description") or "").split("—")[0].strip()[:52]
                             or f"form {i + 1}")
                    out.append((label, d))
                return out
        return [("", n)]

    def child_keys(self, node):
        props = dict(node.get("properties") or {})
        if props:
            return props, False
        for holder in ("additionalProperties", "patternProperties"):
            h = node.get(holder)
            if isinstance(h, dict) and h:
                value = h if "properties" in h else list(h.values())[0]
                return {ANY: value}, True
        return {}, False

    def type_of(self, resolved, raw):
        if isinstance(raw, dict) and raw.get("type") == "array":
            return f"list of {self.deref(raw).get('type') or 'object'}"
        return resolved.get("type") or (raw.get("type") if isinstance(raw, dict) else None) or "—"

    def walk(self, node, path: str, depth: int = 0):
        if depth > 8 or path in self.levels:
            return
        forms = []
        for label, resolved in self.shapes(node):
            props, is_map = self.child_keys(resolved)
            if props:
                forms.append((label, resolved, props, is_map))
        if not forms:
            return

        self.levels[path] = {"path": path, "forms": [], "depth": depth}
        for label, resolved, props, is_map in forms:
            required = set(resolved.get("required") or [])
            keys = []
            for key, raw in props.items():
                res = self.deref(raw)
                desc = (raw.get("description") if isinstance(raw, dict) else None) or res.get("description")
                enum = res.get("enum") or (raw.get("enum") if isinstance(raw, dict) else None)
                child = f"{path}.{key}"
                has_children = bool(self.child_keys(res)[0]) or len(self.shapes(raw)) > 1
                if not desc:
                    self.gaps.append({"level": path, "key": key})
                keys.append({
                    "key": key, "required": key in required,
                    "type": self.type_of(res, raw if isinstance(raw, dict) else {}),
                    "desc": desc,
                    "enum": [(e, self.dotted.get(e)) for e in enum] if enum else None,
                    "child": child if has_children else None,
                })
                self.walk(raw, child, depth + 1)
            self.levels[path]["forms"].append({
                "label": label, "free_key_map": is_map,
                "description": resolved.get("description"),
                "keys": sorted(keys, key=lambda k: (not k["required"], k["key"])),
            })


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# examples, cut from real concepts
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def cut_examples(bundle: pathlib.Path, limit_chars: int = 1400):
    """{level path -> {concept, yaml}} — an example a person TYPED would be another home."""
    examples: dict[str, dict] = {}
    read: list[str] = []
    concepts = bundle / "ontology" / "concepts"
    if not concepts.is_dir():
        return examples, read

    def collect(obj, path, name):
        if path not in examples and isinstance(obj, (dict, list)) and obj:
            text = yaml.safe_dump(obj, sort_keys=False, allow_unicode=True, width=86).rstrip()
            if len(text) <= limit_chars:
                examples[path] = {"concept": name, "yaml": text}
        if isinstance(obj, dict):
            for k, v in obj.items():
                collect(v, f"{path}.{k}", name)
        elif isinstance(obj, list) and obj:
            collect(obj[0], path, name)

    for f in sorted(concepts.glob("*.yaml")):
        try:
            doc = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError:
            continue
        name = (doc.get("concept") or {}).get("name") or f.stem
        read.append(name)
        for top, val in doc.items():
            collect(val, f"concept.{top}", name)
        for src in ((doc.get("grounding") or {}).get("sources") or []):
            cols = src.get("columns")
            if isinstance(cols, dict):
                for spec in cols.values():
                    collect(spec, f"concept.grounding.sources.columns.{ANY}", name)
                    break
    return examples, read


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# rendering
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def slug(path: str) -> str:
    return path.replace(ANY, ANY_SLUG)


def level_file(path: str) -> str:
    return f"{slug(path)}.md"


def notion_file(notion: str) -> str:
    return f"vocabulary/{notion}.md"


def cell(text) -> str:
    """One table cell: pipes escaped and newlines folded, or a table breaks in half."""
    s = " ".join(str(text or "").split())
    return s.replace("|", "\\|")


def render_level(path, level, levels, examples, gaps_by_level, bundle_name) -> str:
    segs = path.split(".")
    crumb = []
    for i in range(len(segs)):
        p = ".".join(segs[:i + 1])
        crumb.append(segs[i] if i == len(segs) - 1
                     else (f"[{segs[i]}]({level_file(p)})" if p in levels else segs[i]))

    out = [BANNER, "", f"# `{path}`", "", " · ".join(crumb), ""]

    description = next((f["description"] for f in level["forms"] if f.get("description")), None)
    if description:
        out += [description.strip(), ""]

    n_gap = len(gaps_by_level.get(path, ()))
    if n_gap:
        out += [f"> **{n_gap} key{'s' if n_gap > 1 else ''} at this level carry no description in "
                f"`mac.schema.json`.** They are marked `— gap —` below. The place to fix one is the "
                f"schema, which is its one home; this page is generated and cannot hold the answer.",
                ""]

    for i, form in enumerate(level["forms"], 1):
        if len(level["forms"]) > 1:
            out += [f"## Form {i}" + (f" — {form['label']}" if form["label"] else ""), ""]
            if form["description"]:
                out += [form["description"].strip(), ""]
        else:
            out += ["## Keys you may write here", ""]

        if form["free_key_map"]:
            out += [f"You choose the names at this level — a column name, an axis name. "
                    f"`{ANY}` below stands for any one of them.", ""]

        out += ["| key | | type | what it means | goes deeper |",
                "|---|---|---|---|---|"]
        for k in form["keys"]:
            meaning = cell(k["desc"]) if k["desc"] else "— gap —"
            if k["enum"]:
                values = []
                for value, term in k["enum"]:
                    if term and term.get("notion"):
                        values.append(f"[`{value}`]({notion_file(term['notion'])}#{term['term']})")
                    else:
                        values.append(f"`{value}`")
                meaning += "<br>**one of:** " + " · ".join(values)
            deeper = f"[{k['child'].split('.')[-1]}]({level_file(k['child'])})" if k["child"] else ""
            out.append(f"| `{k['key']}` | {'**required**' if k['required'] else ''} | "
                       f"`{k['type']}` | {meaning} | {deeper} |")
        out.append("")

    example = examples.get(path)
    if example:
        out += ["## As it is actually written", "",
                f"Cut from **{example['concept']}** in the `{bundle_name}` bundle — not typed by hand.",
                "", "```yaml", example["yaml"], "```", ""]

    children = sorted(p for p in levels
                      if p.startswith(path + ".") and "." not in p[len(path) + 1:])
    if children:
        out += ["## Levels under this one", ""]
        out += [f"- [`{p}`]({level_file(p)})" for p in children]
        out.append("")

    out += ["---", "", f"[↑ the index](README.md)", ""]
    return "\n".join(out)


def render_notion(notion, body, levels) -> str:
    out = [BANNER, "", f"# `mac.{notion}.<term>`", "",
           ("**Closed** — these are all of them. A value outside this list is a load error, "
            "not a new term." if body["closed"] else "**Open** — terms may be added.")
           + f"  ·  {len(body['terms'])} terms", ""]
    if body["description"]:
        out += [body["description"].strip(), ""]

    out += ["## Terms", "", "| term | write it as | what it means |", "|---|---|---|"]
    for term, entry in body["terms"].items():
        extra = entry.get("extra") or {}
        meaning = cell(entry["definition"]) if entry["definition"] else "— no definition —"
        if extra:
            meaning += "<br>" + " · ".join(
                f"`{k}`: {cell(json.dumps(v) if not isinstance(v, str) else v)}"
                for k, v in extra.items())
        out.append(f"| <a id=\"{term}\"></a>`{term}` | `mac.{notion}.{term}` | {meaning} |")
    out.append("")

    takers = []
    for path, level in levels.items():
        for form in level["forms"]:
            for k in form["keys"]:
                if not k["enum"]:
                    continue
                for value, term in k["enum"]:
                    if (term or {}).get("notion") == notion:
                        takers.append((path, k["key"]))
                        break
    takers = sorted(set(takers))
    if takers:
        out += ["## Keys that take one of these values", ""]
        out += [f"- `{k}` on [`{p}`](../{level_file(p)})" for p, k in takers]
        out.append("")

    out += ["---", "", "[↑ the index](../README.md)", ""]
    return "\n".join(out)


def render_index(levels, notions, gaps, examples, schema_version, bundle_name, concepts_read) -> str:
    key_total = sum(len(f["keys"]) for lv in levels.values() for f in lv["forms"])
    described = key_total - len(gaps)
    out = [BANNER, "", "# The key reference", "",
           "Every key a concept file may write, one page per level. Start at "
           "[`concept`](concept.md) — the file itself — and walk down: each page lists the keys "
           "legal at that level, what each means, which are required, the legal values of each, "
           "and the level beneath it.", "",
           f"Generated from `mac.schema.json` **{schema_version}** and `mac_vocabulary.yaml`. "
           f"Examples are cut from {len(concepts_read)} real concepts in the `{bundle_name}` "
           "bundle. Nothing on these pages is authored prose — see "
           "`tools/gen_key_reference.py` for why.", "",
           "| | |", "|---|---|",
           f"| levels | {len(levels)} |",
           f"| keys | {key_total} |",
           f"| described in the schema | **{described} of {key_total}** "
           f"({round(100 * described / max(key_total, 1))}%) |",
           f"| **gaps — admitted and unexplained** | **{len(gaps)}** |",
           f"| vocabularies | {len(notions)}, "
           f"{sum(len(n['terms']) for n in notions.values())} terms |",
           f"| examples | {len(examples)} |", ""]

    out += ["## The levels", "", "| level | keys | gaps |", "|---|---|---|"]
    gaps_by_level: dict[str, int] = {}
    for g in gaps:
        gaps_by_level[g["level"]] = gaps_by_level.get(g["level"], 0) + 1
    for path in sorted(levels):
        n_keys = sum(len(f["keys"]) for f in levels[path]["forms"])
        n_gap = gaps_by_level.get(path, 0)
        out.append(f"| [`{path}`]({level_file(path)}) | {n_keys} | "
                   f"{'**' + str(n_gap) + '**' if n_gap else ''} |")
    out.append("")

    out += ["## The vocabularies and the predefined types", "",
            "A value like `mac.concept.column.measure_type.flow` is the notion "
            "`concept.column.measure_type` and the term `flow`. Each page lists every term of one "
            "notion and every key that accepts it.", "",
            "| notion | terms | closed |", "|---|---|---|"]
    for notion in sorted(notions):
        body = notions[notion]
        out.append(f"| [`mac.{notion}`]({notion_file(notion)}) | {len(body['terms'])} | "
                   f"{'yes' if body['closed'] else 'no'} |")
    out.append("")

    if gaps:
        out += ["## The gaps, by level", "",
                "Each is a key the schema admits and does not explain. The fix is a description "
                "written into `mac.schema.json`; these pages then fill themselves in.", "",
                "| level | keys with no description |", "|---|---|"]
        by: dict[str, list[str]] = {}
        for g in gaps:
            by.setdefault(g["level"], []).append(g["key"])
        for path in sorted(by, key=lambda p: (-len(by[p]), p)):
            out.append(f"| [`{path}`]({level_file(path)}) | "
                       f"{', '.join('`' + k + '`' for k in sorted(by[path]))} |")
        out.append("")
    return "\n".join(out)


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# the model, and the pages
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def build(root: pathlib.Path, bundle: pathlib.Path | None):
    schema, vocab = load(root)
    notions, dotted = harvest_vocabulary(vocab)
    walker = Walker(schema, dotted)
    walker.walk(walker.defs["ConceptFile"], "concept")
    examples, read = cut_examples(bundle) if bundle and bundle.is_dir() else ({}, [])
    return schema, notions, walker, examples, read


def pages_for(root: pathlib.Path, bundle: pathlib.Path | None) -> dict[str, str]:
    schema, notions, walker, examples, read = build(root, bundle)
    gaps_by_level: dict[str, list[str]] = {}
    for g in walker.gaps:
        gaps_by_level.setdefault(g["level"], []).append(g["key"])

    pages = {"README.md": render_index(walker.levels, notions, walker.gaps, examples,
                                      schema["version"], bundle.name if bundle else "none", read)}
    for path, level in walker.levels.items():
        pages[level_file(path)] = render_level(path, level, walker.levels, examples,
                                               gaps_by_level, bundle.name if bundle else "none")
    for notion, body in notions.items():
        pages[notion_file(notion)] = render_notion(notion, body, walker.levels)
    return pages


def write(out_dir: pathlib.Path, pages: dict[str, str]) -> int:
    (out_dir / "vocabulary").mkdir(parents=True, exist_ok=True)
    for rel, text in pages.items():
        p = out_dir / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")
    return len(pages)


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# the check — two different questions, two different rejects
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def check(root: pathlib.Path, out_dir: pathlib.Path, bundle) -> list[str]:
    schema, notions, walker, examples, read = build(root, bundle)
    pages = pages_for(root, bundle)
    rejects: list[str] = []

    on_disk = {str(p.relative_to(out_dir)) for p in out_dir.rglob("*.md")} if out_dir.is_dir() else set()

    for rel in sorted(set(pages) - on_disk):
        rejects.append(f"[missing-page] {rel} — a level the schema admits has no page; regenerate")
    for rel in sorted(on_disk - set(pages)):
        rejects.append(f"[orphan-page] {rel} — a page for a level the schema no longer admits; delete")
    for rel in sorted(set(pages) & on_disk):
        want = pages[rel]
        want = want if want.endswith("\n") else want + "\n"
        if (out_dir / rel).read_text(encoding="utf-8") != want:
            rejects.append(f"[stale-page] {rel} — the declarations moved and the page did not; regenerate")

    #: THE INDEPENDENT ASSERTION. Everything above re-renders and compares, which cannot catch the
    #: RENDERER dropping a key — `gen_schema_shapes.py` reports its page current while omitting
    #: `rulings` for exactly this reason. So: read the keys out of the schema walk and require each
    #: to appear, as a table cell, on the page for its own level. Different question, different
    #: evidence, so the two cannot agree by construction.
    for path, level in walker.levels.items():
        rel = level_file(path)
        text = (out_dir / rel).read_text(encoding="utf-8") if (out_dir / rel).is_file() else ""
        for form in level["forms"]:
            for k in form["keys"]:
                if f"| `{k['key']}` |" not in text:
                    rejects.append(f"[uncovered-key] {path}.{k['key']} — the schema admits this key "
                                   f"and {rel} does not list it")
    return rejects


# ──────────────────────────────────────────────────────────────────────────────────────────────────
# self-test — one mutant per reject class, plus a clean fixture that must pass
# ──────────────────────────────────────────────────────────────────────────────────────────────────

def self_test(bundle) -> int:
    checks = 0
    failures: list[str] = []

    def expect(cond, msg):
        nonlocal checks
        checks += 1
        if not cond:
            failures.append(msg)

    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "keys"
        pages = pages_for(ROOT, bundle)
        write(out, pages)

        expect(check(ROOT, out, bundle) == [], "a freshly written tree must be clean")

        # stale-page
        target = out / "concept.md"
        keep = target.read_text(encoding="utf-8")
        target.write_text(keep.replace("# `concept`", "# `concept` EDITED"), encoding="utf-8")
        expect(any(r.startswith("[stale-page]") for r in check(ROOT, out, bundle)),
               "a hand-edited page must reject as stale-page")
        target.write_text(keep, encoding="utf-8")

        # missing-page
        target.unlink()
        expect(any(r.startswith("[missing-page]") for r in check(ROOT, out, bundle)),
               "a deleted page must reject as missing-page")
        target.write_text(keep, encoding="utf-8")

        # orphan-page
        stray = out / "concept.not_a_level.md"
        stray.write_text("stray\n", encoding="utf-8")
        expect(any(r.startswith("[orphan-page]") for r in check(ROOT, out, bundle)),
               "a page for no level must reject as orphan-page")
        stray.unlink()

        # uncovered-key — the renderer silently dropping a key the schema admits
        gutted = "\n".join(ln for ln in keep.splitlines() if not ln.startswith("| `grounding`"))
        target.write_text(gutted + "\n", encoding="utf-8")
        rejects = check(ROOT, out, bundle)
        expect(any(r.startswith("[uncovered-key]") for r in rejects),
               "a key the schema admits and the page omits must reject as uncovered-key")
        target.write_text(keep, encoding="utf-8")

        expect(check(ROOT, out, bundle) == [], "restoring every mutant must return to clean")

    if failures:
        for f in failures:
            print(f"  [SELF-TEST] {f}")
        print(f"FAIL: gen_key_reference self-test — {len(failures)} of {checks} check(s) failed")
        return 1
    print(f"PASS: gen_key_reference self-test — {checks}/{checks} check(s) over 4 reject class(es)")
    return 0


def resolve_bundle(explicit: str | None) -> pathlib.Path | None:
    """Explicit, then $MAC_BUNDLE, then a worked bundle beside this checkout, then nothing.

    Nothing is LEGAL: a machine with no bundle gets pages with no examples, which is a thinner
    reference and not a broken one. The sibling lookup is `_neighbours.worked_bundles()` — one
    home for that fact, and it finds a bundle by the `mac.project.yaml` it carries rather than by
    naming a repository, so no checkout name is typed into this public repo.
    """
    import os
    for candidate in (explicit, os.environ.get("MAC_BUNDLE")):
        if candidate:
            p = pathlib.Path(candidate)
            return p if p.is_dir() else None
    sys.path.insert(0, str(SELF.parent))
    try:
        import _neighbours
    except ImportError:
        return None
    for b in reversed(_neighbours.worked_bundles()):
        if (b / "ontology" / "concepts").is_dir():
            return b
    return None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if a page is stale, missing or incomplete")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--bundle", help="a bundle to cut examples from (else $MAC_BUNDLE, else the sibling estate)")
    a = ap.parse_args(argv)

    bundle = resolve_bundle(a.bundle)

    if a.self_test:
        return self_test(bundle)

    if a.check:
        rejects = check(ROOT, OUT_DIR, bundle)
        pages = pages_for(ROOT, bundle)
        if rejects:
            for r in rejects[:40]:
                print(f"  {r}")
            if len(rejects) > 40:
                print(f"  … and {len(rejects) - 40} more")
            print(f"FAIL: gen_key_reference — {len(rejects)} reject(s) over {len(pages)} page(s) "
                  f"examined; run `python3 tools/gen_key_reference.py` to regenerate")
            return 1
        print(f"PASS: gen_key_reference — {len(pages)} page(s) current against mac.schema.json and "
              f"mac_vocabulary.yaml, every admitted key covered")
        return 0

    pages = pages_for(ROOT, bundle)
    n = write(OUT_DIR, pages)
    _, notions, walker, examples, read = build(ROOT, bundle)
    key_total = sum(len(f["keys"]) for lv in walker.levels.values() for f in lv["forms"])
    print(f"PASS: gen_key_reference — wrote {n} page(s) to "
          f"{OUT_DIR.relative_to(ROOT)}: {len(walker.levels)} level(s), {len(notions)} vocabular(y/ies), "
          f"{key_total} key(s) of which {key_total - len(walker.gaps)} described and "
          f"{len(walker.gaps)} unexplained; {len(examples)} example(s) cut from "
          f"{len(read)} concept(s) in {bundle.name if bundle else 'no bundle'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
